import { ro } from '../korean-particle';

/**
 * 08.31에 `"느낌 설문"로 이어져`가 학생 화면에 나갔다 — 템플릿에 조사를 박아둔 탓이다.
 * 막다른 길 문구에 풀이법 이름이 들어가므로 그 버그가 다시 나면 여기서 잡힌다.
 */
describe('ro — 받침에 따라 으로/로', () => {
  it('받침이 없으면 로', () => {
    expect(ro('인수분해')).toBe('인수분해로');
    expect(ro('다항식 전개')).toBe('다항식 전개로');
  });

  it('받침이 있으면 으로', () => {
    expect(ro('미분')).toBe('미분으로');
    expect(ro('근의 공식')).toBe('근의 공식으로');
    expect(ro('완전제곱식')).toBe('완전제곱식으로');
    expect(ro('무리수 계산')).toBe('무리수 계산으로');
  });

  it('ㄹ받침은 로', () => {
    expect(ro('서울')).toBe('서울로');
  });

  it('08.31에 틀렸던 그 말', () => {
    expect(ro('느낌 설문')).toBe('느낌 설문으로');
  });

  it('한글이 아니거나 비어 있어도 화면이 안 깨진다', () => {
    expect(ro('')).toBe('로');
    expect(ro('AI')).toBe('AI로');
  });
});
